SELECT NOME_USUARIO, SALDO_PONTOS
  FROM USUARIO_MOOVUP
 WHERE STATUS = 'A'
 ORDER BY SALDO_PONTOS DESC;

SELECT U.NOME_USUARIO,
       COUNT(*) AS VIAGENS,
       SUM(I.KM_PERCORRIDOS) AS KM_TOTAL,
       SUM(I.CO2_EVITADO) AS CO2_TOTAL
  FROM IMPACTO_AMBIENTAL_MOOVPASS I
  JOIN USUARIO_MOOVUP U
    ON U.ID_USUARIO = I.ID_USUARIO
 GROUP BY U.NOME_USUARIO
 ORDER BY CO2_TOTAL DESC;

SELECT MODALIDADE, STATUS,
       COUNT(*) AS QUANTIDADE,
       SUM(TARIFA_REAIS) AS VALOR_TOTAL
  FROM TICKET_DIGITAL
 GROUP BY MODALIDADE, STATUS
 ORDER BY MODALIDADE, STATUS;

SELECT P.TITULO, U.NOME_USUARIO AS AUTOR,
       P.TIPO_POSTAGEM, P.CURTIDAS
  FROM POSTAGEM P
  JOIN USUARIO_MOOVUP U
    ON U.ID_USUARIO = P.ID_USUARIO
 WHERE P.CURTIDAS > 0
 ORDER BY P.CURTIDAS DESC, P.TITULO;

SELECT A.NOME_USUARIO AS SEGUIDOR,
       B.NOME_USUARIO AS SEGUE,
       S.DATA_SEGUIDO
  FROM SEGUIDOR S
  JOIN USUARIO_MOOVUP A
    ON A.ID_USUARIO = S.ID_USUARIO
  JOIN USUARIO_MOOVUP B
    ON B.ID_USUARIO = S.ID_SEGUIDO
 ORDER BY A.NOME_USUARIO, B.NOME_USUARIO;
