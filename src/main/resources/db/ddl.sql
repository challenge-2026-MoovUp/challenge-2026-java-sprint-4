CREATE TABLE USUARIO_MOOVUP (
    ID_USUARIO    VARCHAR2(50)  NOT NULL,
    NOME_USUARIO  VARCHAR2(40)  NOT NULL,
    EMAIL         VARCHAR2(60)  NOT NULL,
    SENHA         VARCHAR2(100) DEFAULT 'trocar123' NOT NULL,
    SALDO_PONTOS  NUMBER(10)    DEFAULT 0 NOT NULL,
    STATUS        CHAR(1)       NOT NULL,
    DATA_CADASTRO DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_USUARIO       PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_USUARIO_NOME  UNIQUE (NOME_USUARIO),
    CONSTRAINT UK_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIO_STATUS CHECK (STATUS IN ('A', 'I')),
    CONSTRAINT CK_USUARIO_SALDO  CHECK (SALDO_PONTOS >= 0),
    CONSTRAINT CK_USUARIO_DATA
        CHECK (DATA_CADASTRO >= DATE '2026-01-01')
);

CREATE TABLE POSTAGEM (
    POSTAGEM_ID   VARCHAR2(36)  NOT NULL,
    TITULO        VARCHAR2(50)  NOT NULL,
    ID_USUARIO    VARCHAR2(50)  NOT NULL,
    CONTEUDO      VARCHAR2(200) NOT NULL,
    IMAGEM        VARCHAR2(300),
    VIDEO         VARCHAR2(350),
    TIPO_POSTAGEM VARCHAR2(15)  NOT NULL,
    CURTIDAS      NUMBER(10)    DEFAULT 0 NOT NULL,
    DATA_POSTAGEM DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_POSTAGEM PRIMARY KEY (POSTAGEM_ID),
    CONSTRAINT FK_POSTAGEM_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO_MOOVUP (ID_USUARIO) ON DELETE CASCADE,
    CONSTRAINT CK_POSTAGEM_TIPO CHECK (TIPO_POSTAGEM IN ('TEXTO', 'IMAGEM', 'VIDEO')),
    CONSTRAINT CK_POSTAGEM_CURTIDAS CHECK (CURTIDAS >= 0),
    CONSTRAINT CK_POSTAGEM_DATA
        CHECK (DATA_POSTAGEM >= DATE '2026-01-01')
);

CREATE TABLE COMENTARIO (
    COMENTARIO_ID   VARCHAR2(36)  NOT NULL,
    POSTAGEM_ID     VARCHAR2(36)  NOT NULL,
    ID_USUARIO      VARCHAR2(50)  NOT NULL,
    CONTEUDO        VARCHAR2(200) NOT NULL,
    CURTIDAS        NUMBER(10)    DEFAULT 0 NOT NULL,
    DATA_COMENTARIO DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_COMENTARIO PRIMARY KEY (COMENTARIO_ID),
    CONSTRAINT FK_COMENTARIO_POSTAGEM FOREIGN KEY (POSTAGEM_ID)
        REFERENCES POSTAGEM (POSTAGEM_ID) ON DELETE CASCADE,
    CONSTRAINT FK_COMENTARIO_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO_MOOVUP (ID_USUARIO) ON DELETE CASCADE,
    CONSTRAINT CK_COMENTARIO_CURTIDAS CHECK (CURTIDAS >= 0),
    CONSTRAINT CK_COMENTARIO_DATA
        CHECK (DATA_COMENTARIO >= DATE '2026-01-01')
);

CREATE TABLE CURTIDA (
    ID_USUARIO   VARCHAR2(50) NOT NULL,
    POSTAGEM_ID  VARCHAR2(36) NOT NULL,
    DATA_CURTIDA DATE         DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_CURTIDA PRIMARY KEY (ID_USUARIO, POSTAGEM_ID),
    CONSTRAINT FK_CURTIDA_USUARIO  FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO_MOOVUP (ID_USUARIO) ON DELETE CASCADE,
    CONSTRAINT FK_CURTIDA_POSTAGEM FOREIGN KEY (POSTAGEM_ID)
        REFERENCES POSTAGEM (POSTAGEM_ID) ON DELETE CASCADE,
    CONSTRAINT CK_CURTIDA_DATA
        CHECK (DATA_CURTIDA >= DATE '2026-01-01')
);

-- ID_USUARIO segue ID_SEGUIDO. As duas colunas apontam para USUARIO_MOOVUP.
CREATE TABLE SEGUIDOR (
    ID_USUARIO   VARCHAR2(50) NOT NULL,
    ID_SEGUIDO   VARCHAR2(50) NOT NULL,
    DATA_SEGUIDO DATE         DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_SEGUIDOR PRIMARY KEY (ID_USUARIO, ID_SEGUIDO),
    CONSTRAINT FK_SEGUIDOR_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO_MOOVUP (ID_USUARIO) ON DELETE CASCADE,
    CONSTRAINT FK_SEGUIDOR_SEGUIDO FOREIGN KEY (ID_SEGUIDO)
        REFERENCES USUARIO_MOOVUP (ID_USUARIO) ON DELETE CASCADE,
    CONSTRAINT CK_SEGUIDOR_PROPRIO CHECK (ID_USUARIO <> ID_SEGUIDO),
    CONSTRAINT CK_SEGUIDOR_DATA
        CHECK (DATA_SEGUIDO >= DATE '2026-01-01')
);

CREATE TABLE TICKET_DIGITAL (
    ID_TICKET         VARCHAR2(50)  NOT NULL,
    MODALIDADE        VARCHAR2(30)  NOT NULL,
    STATUS            VARCHAR2(20)  NOT NULL,
    TARIFA_REAIS      NUMBER(10,2)  NOT NULL,
    CUSTO_EM_PONTOS   NUMBER(10)    NOT NULL,
    DATA_EXPIRACAO    DATE          NOT NULL,
    QR_CODE_HASH      VARCHAR2(255),
    ID_USUARIO        VARCHAR2(50),
    FORMA_RECEBIMENTO VARCHAR2(10),
    CONSTRAINT PK_TICKET PRIMARY KEY (ID_TICKET),
    CONSTRAINT FK_TICKET_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO_MOOVUP (ID_USUARIO),
    CONSTRAINT CK_TICKET_STATUS
        CHECK (STATUS IN ('DISPONIVEL', 'RESERVADO', 'UTILIZADO', 'EXPIRADO')),
    CONSTRAINT CK_TICKET_MODALIDADE CHECK (MODALIDADE IN ('ONIBUS', 'METRO', 'TREM')),
    CONSTRAINT CK_TICKET_FORMA CHECK (FORMA_RECEBIMENTO IN ('QR_CODE', 'RECARGA')),
    CONSTRAINT CK_TICKET_TARIFA CHECK (TARIFA_REAIS > 0),
    CONSTRAINT CK_TICKET_CUSTO  CHECK (CUSTO_EM_PONTOS > 0),
    CONSTRAINT CK_TICKET_DATA
        CHECK (DATA_EXPIRACAO >= DATE '2026-01-01')
);

CREATE TABLE VIAGEM (
    ID_VIAGEM        VARCHAR2(36) NOT NULL,
    ID_USUARIO       VARCHAR2(50) NOT NULL,
    ID_TICKET        VARCHAR2(50) NOT NULL,
    LINHA            VARCHAR2(30) NOT NULL,
    ESTACAO_EMBARQUE VARCHAR2(50) NOT NULL,
    PONTOS_GERADOS   NUMBER(5)    DEFAULT 0 NOT NULL,
    DATA_VIAGEM      DATE         DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_VIAGEM PRIMARY KEY (ID_VIAGEM),
    CONSTRAINT FK_VIAGEM_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO_MOOVUP (ID_USUARIO),
    CONSTRAINT FK_VIAGEM_TICKET  FOREIGN KEY (ID_TICKET)  REFERENCES TICKET_DIGITAL (ID_TICKET),
    CONSTRAINT CK_VIAGEM_PONTOS  CHECK (PONTOS_GERADOS >= 0),
    CONSTRAINT CK_VIAGEM_DATA
        CHECK (DATA_VIAGEM >= DATE '2026-01-01')
);

CREATE TABLE IMPACTO_AMBIENTAL_MOOVPASS (
    ID_IMPACTO         VARCHAR2(50) NOT NULL,
    CO2_EVITADO        NUMBER(10,2) DEFAULT 0 NOT NULL,
    KM_PERCORRIDOS     NUMBER(7,2)  DEFAULT 0 NOT NULL,
    VIAGENS_REALIZADAS NUMBER(5)    DEFAULT 0 NOT NULL,
    DATA_CALCULO       DATE         DEFAULT SYSDATE NOT NULL,
    ID_USUARIO         VARCHAR2(50) NOT NULL,
    ID_TICKET          VARCHAR2(50) NOT NULL,
    MODALIDADE         VARCHAR2(20) NOT NULL,
    ID_VIAGEM          VARCHAR2(36),
    CONSTRAINT PK_IMPACTO PRIMARY KEY (ID_IMPACTO),
    CONSTRAINT FK_IMPACTO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO_MOOVUP (ID_USUARIO),
    CONSTRAINT FK_IMPACTO_TICKET  FOREIGN KEY (ID_TICKET)  REFERENCES TICKET_DIGITAL (ID_TICKET),
    CONSTRAINT FK_IMPACTO_VIAGEM  FOREIGN KEY (ID_VIAGEM)  REFERENCES VIAGEM (ID_VIAGEM),
    CONSTRAINT CK_IMPACTO_MODALIDADE CHECK (MODALIDADE IN ('ONIBUS', 'METRO', 'TREM')),
    CONSTRAINT CK_IMPACTO_CO2     CHECK (CO2_EVITADO >= 0),
    CONSTRAINT CK_IMPACTO_KM      CHECK (KM_PERCORRIDOS >= 0),
    CONSTRAINT CK_IMPACTO_VIAGENS CHECK (VIAGENS_REALIZADAS >= 0),
    CONSTRAINT CK_IMPACTO_DATA
        CHECK (DATA_CALCULO >= DATE '2026-01-01')
);
